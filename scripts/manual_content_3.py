def chapter9(doc):
    h1(doc, "九、权限与安全")

    h2(doc, "（一）权限模型")
    body(doc, "每一次工具调用之前，系统均进行权限判定。"
              "判定结果有三种：放行、询问、拒绝。")
    body(doc, "默认策略为询问，即模型意图修改文件时会弹出确认，"
              "由使用者决定放行一次、始终放行或拒绝。"
              "未命中任何规则的调用，一律按询问处理。")

    h2(doc, "（二）配置方法")
    body(doc, "权限配置以工具类别为键，值为动作或按模式匹配的动作映射。"
              "可配置动作分为三种：放行、询问、拒绝。")

    h3(doc, "1. 整体设置")
    code(doc,
         '{\n'
         '  "permission": {\n'
         '    "edit": "ask",\n'
         '    "bash": "ask",\n'
         '    "webfetch": "allow"\n'
         '  }\n'
         '}')
    body(doc, "亦可使用通配符一次性设定全部工具的默认动作。")

    h3(doc, "2. 按模式细分")
    body(doc, "读取、编辑、检索、列举、执行命令、派发任务、外部目录、"
              "语言服务、技能等类别，支持按文件路径模式分别设定。")
    code(doc,
         '{\n'
         '  "permission": {\n'
         '    "edit": {\n'
         '      "src/**": "allow",\n'
         '      "*.env": "deny",\n'
         '      "**/*.md": "ask"\n'
         '    },\n'
         '    "bash": {\n'
         '      "git status": "allow",\n'
         '      "rm *": "ask"\n'
         '    }\n'
         '  }\n'
         '}')

    h3(doc, "3. 匹配规则")
    body(doc, "当同一类别配置了多条模式规则时，"
              "以最后命中的规则为准；因此书写顺序有讲究，"
              "精确的规则应置于宽泛的规则之后。")

    h2(doc, "（三）权限模式")
    body(doc, "系统另设五种权限模式，可整体切换行为基调。")
    table(doc, [
        ["模式", "含义"],
        ["default", "默认模式，按配置逐次判定"],
        ["acceptEdits", "自动接受文件编辑类操作，其余仍需询问"],
        ["plan", "计划模式，全盘拒绝写入类操作"],
        ["dontAsk", "免询问模式：未命中放行规则的请求直接拒绝，不再挂起等待审批"],
        ["bypassPermissions", "绕过审批（最高权限）"],
    ], widths=[4.6, 10.4])
    note(doc, "dontAsk 用于无法应答审批的场景，如自动化流水线、定时任务。"
              "它不是「默认放行」，而是「默认拒绝」——"
              "要放行某项操作，必须在配置的放行规则中显式列出。"
              "显式写下的拒绝规则在所有模式下都生效，含最高权限模式。")

    h3(doc, "1. 模式与规则的优先关系")
    body(doc, "配置中显式写明的拒绝规则，效力高于任何模式，永远不会被模式覆盖。")
    body(doc, "在最高权限模式下，命令行执行与文件编辑仍保留询问环节，"
              "以确保高危操作始终经人工确认。")

    h2(doc, "（四）审批交互")
    body(doc, "审批时提供三项选择：仅本次放行、始终放行、拒绝。"
              "选择“仅本次放行”只对当次调用生效；"
              "选择“始终放行”会在当前会话内记住该决定；"
              "选择“拒绝”会连带取消本会话中其余待审批的操作。")
    body(doc, "需要特别说明的是，审批结果仅存在于内存中，不写入配置文件，"
              "重启程序后恢复默认询问策略。")

    h2(doc, "（五）路径围栏与拒绝记录")
    body(doc, "以文件路径为判定依据的权限（读取、编辑、写入、补丁、笔记本编辑），"
              "会额外做一层工作目录围栏校验：路径必须落在当前工作目录之内，"
              "越界路径一律拒绝。命令行与网页抓取不走此校验，"
              "因为它们的判定依据是命令或网址，与路径无关。")
    body(doc, "所有被拒绝的请求会记入本地数据库的拒绝流水表，"
              "包含会话标识、权限名称、判定用的模式、拒绝原因与时间，"
              "供事后排查「哪些命令反复被拒、为何被拒」。"
              "记录只增不改，删除会话时随之外键级联清理。")

    h2(doc, "（六）自动批准")
    body(doc, "命令行提供自动批准参数：")
    code(doc,
         "gyc run --auto \"...\"    # 自动批准未被明确拒绝的权限")
    note(doc, "警告：该参数会绕过大量人工确认环节。"
              "在处理重要项目、含敏感数据的环境或生产相关代码时，"
              "严禁使用。建议仅在受控的沙盒环境中使用，"
              "并事先将敏感路径配置为拒绝。")

    h2(doc, "（七）环境变量与数据安全")
    h3(doc, "1. 服务鉴权")
    body(doc, "服务端鉴权通过以下环境变量或命令行参数设置。")
    table(doc, [
        ["名称", "作用"],
        ["GYCCODE_SERVER_USERNAME", "鉴权用户名，默认值为 gyccode"],
        ["GYCCODE_SERVER_PASSWORD", "鉴权密码"],
    ], widths=[6.0, 9.0])
    body(doc, "只要将监听地址改为非本机地址，就必须启用鉴权，否则服务将对网络内所有人开放。")

    h3(doc, "2. 文件与编码安全")
    body(doc, "系统在文件处理方面采取以下措施，以避免破坏既有文件：")
    body(doc, "其一，新建文件统一采用无编码标记的 UTF-8 格式；"
              "修改既有文件时保留其原有编码标记。")
    body(doc, "其二，读取文件时自动探测编码。"
              "带标记的按 UTF-8 处理；无标记且 UTF-8 解析失败时按国标扩展编码处理，"
              "以兼容早期以 GBK 保存的存量文件；探测结果记入缓存，供后续写回时还原。")
    body(doc, "其三，子进程输出自适应解码，"
              "UTF-8 解析失败时自动回退国标扩展编码，"
              "兼容以 GBK 输出的传统程序。")
    body(doc, "其四，提交前自动检查乱码，拦截重复编码产生的乱码文件。")

    h2(doc, "（八）文件备份")
    body(doc, "写入与编辑类工具在改动文件前会自动创建备份，"
              "备份默认保留最近二十份，存放于数据目录下的 backup 子目录。"
              "即便改动不符合预期，亦可从备份中恢复。")

    h2(doc, "（九）破坏性操作的控制")
    body(doc, "对不可逆或影响较大的操作，系统设置了额外的确认环节。")
