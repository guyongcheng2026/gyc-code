def appendix_b(doc):
    h1(doc, "附录 B　端到端场景示例")
    note(doc, "本章给出从零开始的完整操作流程。"
              "每个场景分为“目标、配置、操作、验收”四步，"
              "照做即可完成。命令中的引号在 Windows 的 PowerShell 中"
              "建议保留原样，路径中的反斜杠无需转义。")

    # ------------------------------------------------------------ 场景一
    h2(doc, "一、第一次使用：让 AI 帮你看懂一个陌生项目")

    h3(doc, "步骤一：配置密钥")
    body(doc, "在终端执行，按提示选择服务商并粘贴密钥。")
    code(doc, "gyc providers login")
    body(doc, "随后确认配置已生效。")
    code(doc, "gyc providers list")
    body(doc, "看到“凭据”栏下有条目数，即表示配置成功。")

    h3(doc, "步骤二：进入项目目录")
    code(doc, "gyc D:\\我的项目")

    h3(doc, "步骤三：用只读模式提问")
    body(doc, "在输入框中键入以下内容后回车。")
    code(doc, "这个项目是做什么的？用了什么技术栈？入口在哪里？")
    body(doc, "此处建议保持默认的 build 智能体，"
              "但因为只是要了解情况，"
              "可先按 Tab 切换到 plan 智能体以确保它不会改动文件。")
    note(doc, "若界面无响应或没有按预期切换，可改用命令行方式：\n"
              "gyc run --agent plan \"这个项目是做什么的？用了什么技术栈？\"")
    body(doc, "观察模型的动作：它会先列出文件结构，"
              "再挑关键文件读取，最后给出总结。"
              "整个过程不会修改任何文件。")

    h3(doc, "步骤四：验收")
    body(doc, "确认三件事：回答中提到的入口文件确实存在；"
              "没有出现“文件不存在”一类报错；"
              "用版本控制查看改动，应为空。")
    code(doc, "git status")

    # ------------------------------------------------------------ 场景二
    h2(doc, "二、修改代码：让 AI 实现一个功能")

    h3(doc, "步骤一：先把需求写成文件")
    body(doc, "将需求写入文件而非直接输入，便于反复修改与复用。")
    code(doc,
         "新建 需求.md，内容如下：\n"
         "\n"
         "# 功能需求\n"
         "\n"
         "给 User 模型增加 nickname 字段（可选，字符串）。\n"
         "要求：\n"
         "1. 字段可为空，为空时默认取用户名\n"
         "2. 补充一个单元测试，覆盖有值与无值两种情况\n"
         "3. 不要修改 dist 与 node_modules 目录")

    h3(doc, "步骤二：以只读方式让它先出方案")
    code(doc, "gyc run --agent plan -f ./需求.md \"先给出实现方案，不要改代码\"")
    body(doc, "此步产出一份方案，你可据此判断方向是否正确，"
              "避免模型直接动手后才发现理解有偏差。")

    h3(doc, "步骤三：执行实现")
    code(doc, "gyc run -f ./需求.md \"按刚才的方案实现，并运行测试验证\"")
    body(doc, "此时模型会：读取相关文件、修改模型定义、新增测试文件、"
              "运行测试、若失败则读报错并自行修正，直至通过。"
              "整个过程在工具层面逐步受权限管控。")

    h3(doc, "步骤四：验收")
    body(doc, "第一，查看差异。在界面中打开差异查看器逐条确认，"
              "或执行下列命令。")
    code(doc, "git diff")
    body(doc, "第二，确认测试通过。")
    code(doc, "bun run test")
    body(doc, "第三，确认无非预期改动。")
    code(doc, "git status")
    body(doc, "若改动超出预期范围，立即告知模型回退，或从备份目录恢复文件。")

    # ------------------------------------------------------------ 场景三
    h2(doc, "三、只读分析：不改动任何文件地评估代码质量")

    h3(doc, "操作")
    code(doc, "gyc run --agent plan \"评估这个项目的代码质量，指出最需要改进的三处，并说明理由\"")
    body(doc, "另一种做法是在配置中把编辑权限设为拒绝，"
              "这样即便误用了 build 智能体也无法改动文件。")
    code(doc,
         '{\n'
         '  "permission": {\n'
         '    "edit": "deny",\n'
         '    "bash": "ask"\n'
         '  }\n'
         '}')
    body(doc, "配置文件改动须重启程序方可生效。")

    # ------------------------------------------------------------ 场景四
    h2(doc, "四、安全加固：保护密钥文件")

    h3(doc, "场景描述")
    body(doc, "希望模型永远不要改动 .env 文件，"
              "但可以自由修改源码。")

    h3(doc, "配置")
    code(doc,
         '{\n'
         '  "permission": {\n'
         '    "edit": {\n'
         '      "**/*.env": "deny",\n'
         '      "**/*.key": "deny",\n'
         '      "**/*.pem": "deny",\n'
         '      "**": "ask"\n'
         '    }\n'
         '  }\n'
         '}')
    body(doc, "四条规则的匹配顺序有讲究："
              "系统以最后命中的规则为准，"
              "因此精确的拒绝规则必须写在宽泛规则之后。")

    h3(doc, "验证")
    body(doc, "让模型尝试修改 .env 文件，它应被直接拒绝而非弹窗询问。")
    code(doc, "gyc run \"把 .env 里的端口号改成 8080\"")
    body(doc, "预期结果：模型被告知该操作被禁止，文件未发生变化。")

    # ------------------------------------------------------------ 场景五
    h2(doc, "五、成本控制：把每轮开销压下来")

    h3(doc, "步骤一：先看清现状")
    code(doc, "gyc stats")
    body(doc, "重点关注“平均”与“中位数”的差距。"
              "若中位数远低于平均值，说明少数超大会话在吃钱。")

    h3(doc, "步骤二：找出贵的会话")
    code(doc, "gyc task list")

    h3(doc, "步骤三：设置轻量模型承担摘要任务")
    code(doc,
         '{\n'
         '  "small_model": "deepseek/deepseek-flash",\n'
         '  "compaction": {\n'
         '    "enabled": true\n'
         '  }\n'
         '}')
    body(doc, "上下文压缩会调用模型生成摘要，"
              "指定轻量模型可显著降低这部分开销。")

    h3(doc, "步骤四：及时压缩会话")
    body(doc, "在界面中按 leader+c，"
              "将长对话压缩为摘要后继续，"
              "可大幅减少后续每轮的输入量。")

    h3(doc, "步骤五：核对效果")
    code(doc, "gyc stats --days 7")
    body(doc, "一周后再看，缓存命中率若明显偏低，"
              "说明会话前缀不够稳定，"
              "可考虑在切换话题时主动开启新会话。")

    # ------------------------------------------------------------ 场景六
    h2(doc, "六、团队协作：让新人复用老手的经验")

    h3(doc, "步骤一：把经验整理成技能")
    code(doc,
         "新建目录与文件：\n"
         ".gyccode/skills/接口测试/SKILL.md\n\n"
         "内容：\n"
         "---\n"
         "name: 接口测试\n"
         "description: 编写或修复接口的自动化测试时使用\n"
         "---\n\n"
         "# 接口测试\n\n"
         "## 何时使用\n"
         "当需要为接口新增测试，或接口测试失败需要排查时。\n\n"
         "## 如何做\n"
         "1. 先阅读既有测试文件，沿用其风格。\n"
         "2. 新增测试置于同级目录，命名保持一致。\n"
         "3. 运行测试命令验证，全部通过方可结束。\n\n"
         "## 常见错误\n"
         "- 忘记清理测试数据，导致影响其他用例。\n"
         "- 断言过于具体，重构后必然失败。")

    h3(doc, "步骤二：把项目规矩写进配置")
    code(doc,
         '{\n'
         '  "instructions": [\n'
         '    "提交信息一律使用简体中文",\n'
         '    "改动前先阅读相关文件",\n'
         '    "注释使用简体中文",\n'
         '    "不要修改 dist 与 node_modules 目录",\n'
         '    "测试文件命名与被测文件保持一致"\n'
         '  ]\n'
         '}')
    body(doc, "配置改动须重启程序方可生效。"
              "该配置可随项目提交至版本库，"
              "使所有成员自动遵循同一套规矩。")

    h3(doc, "步骤三：验证技能已被识别")
    body(doc, "在界面中输入斜杠符号，"
              "确认技能列表中出现“接口测试”。")
    code(doc, "gyc learning status")
    body(doc, "若技能存放在项目目录而非自建技能库，"
              "此命令不会显示它，"
              "此时应以界面中的斜杠列表为准。")

    # ------------------------------------------------------------ 场景七
    h2(doc, "七、并行处理：同时推进多件独立的事")

    h3(doc, "场景描述")
    body(doc, "需要为三个互不依赖的模块分别增加测试文件，"
              "串行处理耗时较长。")

    h3(doc, "操作")
    code(doc, "gyc run \"同时为用户、订单、商品三个模块各新增一个测试文件，分别放在各自目录下，用 team 方式并行推进\"")
    body(doc, "模型会派出多个子智能体并行处理，"
              "各自独立读取与写入，最后汇总结果。")

    h3(doc, "更精确的用法")
    body(doc, "明确告知每个子任务的边界，可减少冲突。")
    code(doc,
         "gyc run \"用 team 方式并行完成：\n"
         "1. 子任务一：为 src/user.ts 补充单元测试\n"
         "2. 子任务二：为 src/order.ts 补充单元测试\n"
         "3. 子任务三：为 src/product.ts 补充单元测试\n"
         "三个子任务互不依赖，最后统一运行测试验证\"")

    h3(doc, "验收")
    code(doc, "git status")
    code(doc, "bun run test")

    # ------------------------------------------------------------ 场景八
    h2(doc, "八、服务化：在一台机器上多处使用")

    h3(doc, "步骤一：启动服务并设置密码")
    code(doc, "gyc serve --port 4096 --hostname 0.0.0.0 -p 你的强密码")
    note(doc, "警告：指定非本机地址等同于在网络上开放服务，"
              "必须设置密码。建议同时在防火墙上限制来源地址，"
              "且不要将端口直接映射至公网。")

    h3(doc, "步骤二：在其他终端接入")
    code(doc, "gyc attach http://127.0.0.1:4096 -p 你的强密码")
    body(doc, "会话与配置完全共享。"
              "亦可在另一台机器上接入，"
              "将地址换为服务端的局域网地址即可。")

    h3(doc, "步骤三：指定远程工作目录")
    code(doc, "gyc attach http://192.168.1.100:4096 -p 密码 --dir /远程/项目路径")

    # ------------------------------------------------------------ 场景九
    h2(doc, "九、故障处理：模型卡住不动怎么办")

    h3(doc, "情况一：任务跑飞了")
    body(doc, "按 Esc 中断当前任务。此操作立即生效，不必等待。")

    h3(doc, "情况二：想保留现场排查")
    body(doc, "中断后可执行下列命令导出该会话，再交由他人分析。")
    code(doc, "gyc export 会话ID -o 现场.json")

    h3(doc, "情况三：怀疑状态已损坏")
    body(doc, "开启一个新会话继续，原会话保留以便对照。")
    code(doc, "gyc run \"从头开始：<简明描述背景与目标>\"")

    h3(doc, "情况四：整体行为异常")
    body(doc, "按五步排查法依次尝试。")
    code(doc,
         "gyc --log-level DEBUG --print-logs run \"你的问题\"  # 一、查日志\n"
         "gyc --pure run \"你的问题\"                           # 二、排除插件\n"
         "bun run dev                                           # 三、排除产物陈旧\n"
         "gyc db query \"SELECT count(*) FROM session\"          # 四、检查数据\n"
         "gyc                                                   # 五、界面按 Ctrl+Alt+K 查键位")


def appendix_c(doc):
    h1(doc, "附录 C　功能触发示例")
    note(doc, "说明：内置工具由模型自动调用，使用者一般不直接操作。"
              "但了解“在什么场景下模型会调用哪个工具”，"
              "有助于更好地下达指令、预判结果。"
              "本章按使用场景给出提示词示例与预期发生的工具调用。")

    h2(doc, "一、引导模型使用特定工具")

    h3(doc, "场景：让模型先读文件再动手")
    code(doc,
         "gyc run \"先读一下 src/user.ts，告诉我它现在是怎么实现的，"
         "暂时不要改任何东西\"")
    body(doc, "预期：模型调用 read 工具读取文件，随后仅作说明。")

    h3(doc, "场景：全库检索某个符号")
    code(doc, "gyc run \"全库搜索 User 这个符号在哪里被使用，用 grep 工具，列出全部位置\"")
    body(doc, "预期：调用 grep 工具，返回匹配列表。"
              "受一百条上限约束，超出部分不再返回。")

    h3(doc, "场景：按文件名模式找文件")
    code(doc, "gyc run \"用 glob 找出项目里所有以 .test.ts 结尾的文件\"")
    body(doc, "预期：调用 glob 工具，列出匹配文件。")

    h3(doc, "场景：分段读取大文件")
    code(doc,
         "gyc run \"src/bundle.js 很大，请先读前 200 行，"
         "告诉我它的结构；需要时再用 offset 继续读后面的内容\"")
    body(doc, "预期：调用 read 工具并使用 offset 与 limit 参数分段读取，"
              "避免一次性载入过多内容。")

    h3(doc, "场景：让模型跑测试并自我修正")
    code(doc, "gyc run \"运行测试，如果失败就读报错并修复，直到全部通过\"")
    body(doc, "预期：调用 bash 工具执行测试命令，"
              "失败后读报错内容、修改代码、再次执行，循环直至通过。")

    h3(doc, "场景：长时命令后台执行")
    code(doc,
         "gyc run \"用后台方式启动开发服务，然后用 bash_background "
         "定期查看它的输出，确认启动成功后告诉我端口号\"")
    body(doc, "预期：bash 工具以 background 模式启动，"
              "随后调用 bash_background 查询状态。")

    h3(doc, "场景：联网查资料")
    code(doc, "gyc run \"用 webfetch 抓取这个文档页面，整理成要点：https://example.com/doc\"")
    body(doc, "预期：调用 webfetch 工具，"
              "按 markdown 格式返回并由模型整理。"
              "该工具无需额外授权。")

    h3(doc, "场景：检索类需求")
    code(doc, "gyc run \"搜索 2026 年主流代码助手的定价方案，做成对比表\"")
    body(doc, "预期：调用 websearch 工具。"
              "该工具仅在内置服务商可用或已开启外部检索开关时提供，"
              "否则请改用 webfetch 直接抓取已知网址。")

    h3(doc, "场景：查看界面渲染效果")
    code(doc, "gyc run \"用 browser 工具打开 http://localhost:3000 截图，"
              "看看首屏布局有没有问题\"")
    body(doc, "预期：调用 browser 工具截图并回看。"
              "该工具不会点击或滚动，"
              "截图落盘于数据目录下的 screenshots 子目录。")

    h3(doc, "场景：版本控制操作")
    code(doc,
         "gyc run \"用 git_status 看当前有哪些改动，"
         "再用 git_diff 看看具体改了什么\"")
    body(doc, "预期：依次调用 git_status 与 git_diff。"
              "六个版本控制工具仅在项目为版本控制仓库时提供。")

    h3(doc, "场景：提交代码")
    code(doc, "gyc run \"我已经把文件暂存好了，用 git_commit 提交，"
         "提交信息写'修复登录页空指针'\"")
    body(doc, "预期：调用 git_commit。"
              "该工具默认仅提交已暂存内容，不会顺带提交其他改动；"
              "必须提供提交信息。")
    note(doc, "更稳妥的做法是由使用者自行执行提交命令，"
              "把提交这一步留在自己掌控之下：\n"
              "git add -A\n"
              "git commit -m \"修复登录页空指针\"")

    h3(doc, "场景：多任务并行")
    code(doc, "gyc run \"用 swarm 派出一个团队，同时检查前端和后端的问题\"")
    body(doc, "预期：调用 swarm 工具派出并行子智能体团队。")

    h3(doc, "场景：让模型向你确认")
    code(doc, "gyc run \"在动手之前，遇到需要我做技术决策的地方请用 question 问我\"")
    body(doc, "预期：调用 question 工具征询，"
              "弹出选项由你选定，避免模型自行臆断。")

    h3(doc, "场景：维护任务清单")
    code(doc, "gyc run \"这是一个多步骤任务，请用 todowrite 维护进度，每完成一步就更新\"")
    body(doc, "预期：调用 todowrite 工具更新任务状态，便于你随时了解进展。")

    h2(doc, "二、工具选择的经验法则")
    table(doc, [
        ["你想让模型做什么", "应当怎么说"],
        ["读文件内容", "说明文件路径，并提示先读后改"],
        ["搜索代码内容", "明确要求用 grep 工具，并说明搜索词"],
        ["按名字找文件", "明确要求用 glob 工具，并给出模式"],
        ["运行命令", "直接说明要执行的命令，让模型调用 bash"],
        ["查看改动", "要求用 git_status 或 git_diff"],
        ["控制任务规模", "三步以上的任务要求用 todowrite 维护进度"],
        ["减少来回沟通", "把需求写进文件后用 -f 附加，避免反复澄清"],
        ["避免误改文件", "使用 plan 智能体，或在配置中将 edit 设为拒绝"],
        ["控制花费", "要求先出方案再动手，避免直接大范围改动"],
    ], widths=[4.6, 10.4])
    note(doc, "一般而言，无需刻意指定工具。"
              "模型会自行选择合适的工具。"
              "但当任务复杂、模型选错工具时，"
              "上述提示方式可有效纠正。")
